function readStoredLang() {
  try {
    if (typeof localStorage !== 'undefined') {
      return localStorage.getItem(LANG_STORAGE_KEY) === 'zh' ? 'zh' : 'en';
    }
  } catch {
    // Ignore storage access errors
  }
  return 'en';
}

let currentLang = readStoredLang();

export function getLang() {
  try {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem(LANG_STORAGE_KEY);
      if (saved === 'zh') {
        currentLang = 'zh';
        return 'zh';
      }
      if (saved === 'en') {
        currentLang = 'en';
        return 'en';
      }
    }
  } catch {
    // Ignore storage access errors
  }
  return currentLang === 'zh' ? 'zh' : 'en';
}

export function setLangCode(lang) {
  const norm = lang === 'zh' ? 'zh' : 'en';
  currentLang = norm;
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(LANG_STORAGE_KEY, norm);
    }
  } catch {
    // Ignore storage quota or privacy mode errors
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = norm === 'zh' ? 'zh-CN' : 'en';
    document.title = t('app.title');
  }
  return norm;
}

export function getLocaleTag() {
  return currentLang === 'zh' ? 'zh-CN' : 'en-US';
}

export function t(key, params = {}) {
  const dict = MESSAGES[currentLang] || MESSAGES.en;
  const template = dict[key] ?? MESSAGES.en[key] ?? key;
  if (!params || typeof params !== 'object') {
    return String(template);
  }
  return String(template).replace(/\{(\w+)\}/g, (match, name) => {
    if (
      Object.prototype.hasOwnProperty.call(params, name) &&
      params[name] !== undefined &&
      params[name] !== null
    ) {
      return String(params[name]);
    }
    return match;
  });
}
